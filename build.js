#!/usr/bin/env node
// Build the spin CLI into a SINGLE self-contained ESM bundle (deps inlined) so the
// plugin runs offline with no node_modules. Also typechecks with tsc.
// The bundle lands at dist/cli/index.js; bin/spin.js imports it.

import * as esbuild from 'esbuild';
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, cpSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

const require = createRequire(import.meta.url);

console.log('Type-checking (tsc --noEmit)...');
try {
  const tscPath = require.resolve('typescript/bin/tsc');
  execFileSync(process.execPath, [tscPath, '--noEmit'], { stdio: 'inherit' });
} catch {
  console.error('Type-check failed.');
  process.exit(1);
}

if (existsSync('dist')) rmSync('dist', { recursive: true, force: true });

console.log('Bundling with esbuild...');
await esbuild.build({
  entryPoints: ['src/cli/index.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  outfile: 'dist/cli/index.js',
  // Some bundled CJS deps reference require(); provide it in the ESM bundle.
  banner: {
    js: "import { createRequire as __cr } from 'module'; const require = __cr(import.meta.url);",
  },
});

// Sync the self-contained bundle + schemas INTO plugin/ so that, on a real Claude
// Code install, ${CLAUDE_PLUGIN_ROOT} (= plugin/) resolves ${CLAUDE_PLUGIN_ROOT}/dist
// and the CLI finds plugin/schemas/. Without this the plugin's `spin` shorthand
// would point at a non-existent path. (The repo-root dist/ + schemas/ remain for
// npm/vitest.)
console.log('Syncing bundle + schemas into plugin/...');
for (const sub of ['dist', 'schemas']) {
  rmSync(`plugin/${sub}`, { recursive: true, force: true });
  cpSync(sub, `plugin/${sub}`, { recursive: true });
}

console.log('Regenerating verification/inventory.json from source...');
execFileSync(process.execPath, ['scripts/gen-inventory.js'], { stdio: 'inherit' });

// --- dist-integrity witness -------------------------------------------------
// sha256 (node:crypto, dependency-free) of the two built CLI bundles + every
// schema file, keyed by repo-relative path. `spin verify-self` recomputes these
// and compares — a hand-edited dist (the CLAUDE.md invariant: "dist is BUILD
// OUTPUT, never hand-edit") or a schemas/plugin-schemas drift shows up as a
// named mismatch instead of silently shipping.
console.log('Writing verification/checksums.json...');
writeChecksumManifest();

function sha256File(filePath) {
  return createHash('sha256').update(readFileSync(filePath)).digest('hex');
}

/** Recursively list files under `dir` (repo-relative, forward-slash-joined). */
function listFilesRecursive(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...listFilesRecursive(rel));
    else if (entry.isFile()) out.push(rel);
  }
  return out;
}

function writeChecksumManifest() {
  const targets = [
    'dist/cli/index.js',
    'plugin/dist/cli/index.js',
    ...listFilesRecursive('schemas'),
    ...listFilesRecursive('plugin/schemas'),
  ];
  const files = {};
  for (const rel of targets) {
    if (!existsSync(rel)) continue; // defensive; every target should exist post-build
    files[rel] = sha256File(rel);
  }
  const manifest = {
    note:
      'Generated by build.js — sha256 of the two built CLI bundles + every schema file. ' +
      'Do not hand-edit. Verify with `spin verify-self`.',
    generatedAt: new Date().toISOString(),
    files,
  };
  mkdirSync('verification', { recursive: true });
  writeFileSync('verification/checksums.json', JSON.stringify(manifest, null, 2) + '\n');
}

console.log('Build completed: dist/cli/index.js (+ plugin/dist, plugin/schemas, verification/checksums.json).');
